/** Bump when the JSON changes in a way that breaks comparing two files. */
export const FORMAT = 1;

const SCRIPT = fileURLToPath(import.meta.url);
const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const PHASES = ['cold', 'warm', 'reopen'] as const;
export const METRICS = ['scanMs', 'coldMs', 'warmMs', 'reopenMs', 'hoverColdMs', 'hoverWarmMs', 'paletteMs'] as const;

/** What each metric measured, saved with the numbers. */
const CONDITIONS: Record<Metric, string> = {
  scanMs: 'scanVault alone; file contents are not read.',
  coldMs:
    'New index (openIndex + syncIndex, scan included). Notes written by the parent process ' +
    '(system Node) and not read since by the benchmark; not a cold disk: the OS may cache them.',
  warmMs: 'Another new index (scan included) over notes the measuring process has already read.',
  reopenMs: 'The warm index again with nothing changed (scan and mtime + size check).',
  hoverColdMs: 'Cold hover preview fetch from disk into NoteCache.',
  hoverWarmMs: 'Warm hover preview lookup from NoteCache.',
  paletteMs: 'One keystroke of the `Ctrl+P` search over every note path: the slowest of a few queries (median of 7 each).',
};

type Phase = (typeof PHASES)[number];
type Metric = (typeof METRICS)[number];
export type Runtime = 'node' | 'electron';

interface Measurement {
  scanMs: number;
  coldMs: number;
  warmMs: number;
  reopenMs: number;
  hoverColdMs: number;
  hoverWarmMs: number;
  paletteMs: number;
  /** What `syncIndex` reported in each phase. */
  sync: Record<Phase, SyncReport>;
  /** Size of the closed index. */
  dbBytes: number;
  versions: { node: string; electron: string | null; sqlite: string; betterSqlite3: string };
}

export type Run = Omit<Measurement, 'versions'> & {
  /** Busy share of all CPUs during the second before the run, 0 to 100. */
  cpuBusyPercent: number;
};

export interface Stats {
  min: number;
  median: number;
  max: number;
  /** (max - min) / median, in percent. */
  spreadPercent: number;
}

export interface SizeResult {
  notes: number;
  /** `hash` identifies the vault: only compare results whose hashes match. */
  vault: { hash: string; links: number; bytes: number; folders: number };
  summary: Record<Metric, Stats>;
  runs: Run[];
}

export interface BenchReport {
  format: number;
  createdAt: string;
  /** Free text about the conditions, from `--label`. */
  label: string | null;
  machine: { os: string; release: string; arch: string; cpu: string; threads: number; memoryGB: number };
  versions: Measurement['versions'] & {
    indexSchema: number;
    commit: string | null;
    /** Uncommitted changes in the working tree. */
    dirty: boolean | null;
  };
  /** The measuring process. `electron-as-node` is not the app. */
  runtime: 'node' | 'electron-as-node';
  conditions: Record<Metric, string>;
  seed: number;
  results: SizeResult[];
}

const round = (value: number) =>
  value < 1 ? Math.round(value * 10000) / 10000 : Math.round(value * 10) / 10;

export function stats(values: number[]): Stats {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = sorted.length >> 1;
  const median = sorted.length % 2 ? sorted[middle]! : (sorted[middle - 1]! + sorted[middle]!) / 2;
  const min = sorted[0]!;
  const max = sorted.at(-1)!;
  return { min, median: round(median), max, spreadPercent: median > 0 ? round(((max - min) / median) * 100) : 0 };
}

async function timed<T>(work: () => Promise<T>): Promise<[number, T]> {
  const start = performance.now();
  const result = await work();
  return [round(performance.now() - start), result];
}

/** A sync that did less work than expected would look fast: fail instead. */
function check(phase: Phase, report: SyncReport, notes: number): void {
  const indexed = phase === 'reopen' ? 0 : notes;
  if (report.notes !== notes || report.indexed !== indexed || report.failed !== 0) {
    throw new Error(`${phase} sync of ${notes} notes is not valid: ${JSON.stringify(report)}`);
  }
}

/** The slowest of a broad, an exact, a full path, a short folder and an unmatched query. */
function paletteKeystroke(paths: string[]): number {
  const search = createNoteSearch(paths);
  const last = paths.at(-1) ?? 'none.md';
  const exact = last.slice(last.lastIndexOf('/') + 1, -'.md'.length);
  // A `/` searches whole paths: from a note in a folder, if any.
  const nested = paths.findLast((path) => path.includes('/')) ?? last;
  const folder = nested.slice(0, nested.indexOf('/'));
  const queries = [exact.slice(0, 1), exact, nested.slice(0, -'.md'.length), `${folder.slice(0, 2)}/`, 'a/', 'qqzzxx'];
  const costs = queries.map((query) => {
    const times = Array.from({ length: 7 }, () => {
      const start = performance.now();
      search(query, 50);
      return performance.now() - start;
    });
    return stats(times).median;
  });
  return Math.max(0.0001, round(Math.max(...costs)));
}

/** Runs in its own process. `vault` must be freshly generated; `userData` must be empty. */
async function measure(vault: string, userData: string, notes: number): Promise<Measurement> {
  const [scanMs, tree] = await timed(() => scanVault(vault));
  const firstNote = (function findFirst(entries: typeof tree): string | null {
    for (const entry of entries) {
      if (entry.kind === 'note') return entry.path;
      const nested = findFirst(entry.children);
      if (nested) return nested;
    }
    return null;
  })(tree);

  const index = async (phase: Phase, file: string) => {
    const [ms, report] = await timed(async () => {
      const db = openIndex(file);
      try {
        return await syncIndex(db, vault, new AbortController().signal);
      } finally {
        db.close();
      }
    });
    check(phase, report, notes);
    return { ms, report };
  };
  const warmFile = indexPath(userData, 'warm');
  const cold = await index('cold', indexPath(userData, 'cold'));
  const warm = await index('warm', warmFile);
  const reopen = await index('reopen', warmFile);

  const paths: string[] = [];
  (function collect(entries: typeof tree): void {
    for (const entry of entries) {
      if (entry.kind === 'note') paths.push(entry.path);
      else collect(entry.children);
    }
  })(tree);
  const paletteMs = paletteKeystroke(paths);

  const cache = createNoteCache({
    getPreviews: async (paths) =>
      Promise.all(paths.map((p) => readNotePreview(join(vault, p), p))),
    onVaultEvents: () => () => {},
  });
  const [hoverColdMs] = firstNote ? await timed(() => cache.fetch(firstNote)) : [0];
  const warmStart = performance.now();
  if (firstNote) {
    for (let i = 0; i < 10_000; i++) cache.peek(firstNote);
  }
  const hoverWarmMs = Math.max(0.0001, round((performance.now() - warmStart) / 10_000));
  cache.stop();

  const memory = new Database(':memory:');
  const sqlite = memory.prepare('SELECT sqlite_version()').pluck().get() as string;
  memory.close();
  const betterSqlite3 = (createRequire(import.meta.url)('better-sqlite3/package.json') as { version: string }).version;

  return {
    scanMs,
    coldMs: cold.ms,
    warmMs: warm.ms,
    reopenMs: reopen.ms,
    hoverColdMs,
    hoverWarmMs,
    paletteMs,
    sync: { cold: cold.report, warm: warm.report, reopen: reopen.report },
    dbBytes: (await stat(warmFile)).size,
    versions: { node: process.versions.node, electron: process.versions.electron ?? null, sqlite, betterSqlite3 },
  };
}

const exec = promisify(execFile);

async function measureInChild(runtime: Runtime, vault: string, userData: string, notes: number): Promise<Measurement> {
  const env = { ...process.env };
  let binary = process.execPath;
  delete env.ELECTRON_RUN_AS_NODE;
  if (runtime === 'electron') {
    // From Node, the `electron` package is the path of its binary.
    binary = createRequire(import.meta.url)('electron') as unknown as string;
    env.ELECTRON_RUN_AS_NODE = '1';
  }
  const { stdout } = await exec(binary, [SCRIPT, '--measure', vault, userData, String(notes)], {
    env,
    maxBuffer: 1024 * 1024,
  });
  return JSON.parse(stdout) as Measurement;
}

function cpuTimes(): { idle: number; total: number } {
  let idle = 0;
  let total = 0;
  for (const { times } of cpus()) {
    idle += times.idle;
    total += times.user + times.nice + times.sys + times.idle + times.irq;
  }
  return { idle, total };
}

export async function cpuBusyPercent(): Promise<number> {
  const before = cpuTimes();
  await sleep(1000);
  const after = cpuTimes();
  return round(100 * (1 - (after.idle - before.idle) / (after.total - before.total)));
}

async function git(...args: string[]): Promise<string | null> {
  return exec('git', args, { cwd: REPO_ROOT }).then(
    ({ stdout }) => stdout.trim(),
    () => null,
  );
}

export interface BenchOptions {
  sizes: number[];
  runs: number;
  seed: number;
  runtime: Runtime;
  label?: string;
  log?: (line: string) => void;
}

export async function runBench(options: BenchOptions): Promise<BenchReport> {
  const { sizes, runs, seed, runtime, log = () => {} } = options;
  if (sizes.length === 0) throw new Error('sizes must not be empty');
  if (!Number.isInteger(runs) || runs < 1) throw new Error('runs must be an integer >= 1');

  const commit = await git('rev-parse', 'HEAD');
  const changes = await git('status', '--porcelain');
  let versions: Measurement['versions'] | undefined;
  const results: SizeResult[] = [];

  for (const notes of sizes) {
    const done: Run[] = [];
    let vault: SizeResult['vault'] | undefined;
    for (let run = 1; run <= runs; run++) {
      const work = await mkdtemp(join(tmpdir(), 'myelin-bench-run-'));
      try {
        log(`${notes} notes, run ${run}/${runs}: generating`);
        const { hash, links, bytes, folders } = await generateVault({ notes, seed, out: join(work, 'vault') });
        vault = { hash, links, bytes, folders };
        const busy = await cpuBusyPercent();
        log(`${notes} notes, run ${run}/${runs}: measuring (CPU ${busy}% busy)`);
        const { versions: found, ...measured } = await measureInChild(
          runtime, join(work, 'vault'), join(work, 'userData'), notes,
        );
        versions = found;
        done.push({ cpuBusyPercent: busy, ...measured });
        log(METRICS.map((metric) => `  ${metric} ${measured[metric]}`).join(''));
      } finally {
        // Windows may hold a file for a moment (antivirus, indexer).
        await rm(work, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }).catch((error: unknown) => {
          log(`could not delete ${work}: ${String(error)}`);
        });
      }
    }
    const summary = Object.fromEntries(
      METRICS.map((metric) => [metric, stats(done.map((run) => run[metric]))]),
    ) as Record<Metric, Stats>;
    results.push({ notes, vault: vault!, summary, runs: done });
  }

  return {
    format: FORMAT,
    createdAt: new Date().toISOString(),
    label: options.label ?? null,
    machine: {
      os: osVersion(),
      release: release(),
      arch: process.arch,
      cpu: cpus()[0]?.model.trim() ?? 'unknown',
      threads: cpus().length,
      memoryGB: round(totalmem() / 2 ** 30),
    },
    versions: {
      ...versions!,
      indexSchema: SCHEMA_VERSION,
      commit,
      dirty: changes === null ? null : changes !== '',
    },
    runtime: runtime === 'electron' ? 'electron-as-node' : 'node',
    conditions: CONDITIONS,
    seed,
    results,
  };
}

export function formatReport(report: BenchReport): string {
  const { machine, versions } = report;
  const lines = [
    `${machine.os} ${machine.release}, ${machine.cpu}, ${machine.threads} threads, ${machine.memoryGB} GB`,
    `${report.runtime}: Node ${versions.node}${versions.electron ? `, Electron ${versions.electron}` : ''}, ` +
      `SQLite ${versions.sqlite}, better-sqlite3 ${versions.betterSqlite3}`,
    `commit ${versions.commit?.slice(0, 7) ?? 'unknown'}${versions.dirty ? ' (dirty)' : ''}, seed ${report.seed}` +
      (report.label ? `, ${report.label}` : ''),
    'cold = new index, notes never read since written; warm = new index, notes already read;',
    'reopen = no changes. cold, warm and reopen include a vault scan.',
  ];
  for (const { notes, runs, summary, vault } of report.results) {
    const busy = stats(runs.map((run) => run.cpuBusyPercent));
    lines.push(
      '',
      `${notes} notes (vault ${vault.hash.slice(0, 8)}), ${runs.length} run(s), ` +
        `index ${round(runs.at(-1)!.dbBytes / 1e6)} MB, CPU busy before a run ${busy.min}-${busy.max}%`,
      `${'ms'.padEnd(10)}${['median', 'min', 'max', 'spread'].map((head) => head.padStart(10)).join('')}`,
    );
    for (const metric of METRICS) {
      const { median, min, max, spreadPercent } = summary[metric];
      const cells = [median, min, max, `${spreadPercent}%`].map((cell) => String(cell).padStart(10));
      lines.push(`${metric.slice(0, -'Ms'.length).padEnd(10)}${cells.join('')}`);
    }
  }
  return lines.join('\n');
}

export function isInside(parent: string, child: string): boolean {
  const path = relative(parent, child);
  return path !== '..' && !path.startsWith(`..${sep}`) && !isAbsolute(path);
}

async function main(): Promise<void> {
  if (process.argv[2] === '--editor') {
    const { benchEditor } = await import('./bench-editor.ts');
    return benchEditor(process.argv.slice(3));
  }
  if (process.argv[2] === '--graph') {
    const { benchGraph } = await import('./bench-graph.ts');
    return benchGraph(process.argv.slice(3));
  }
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      sizes: { type: 'string', default: '10000,100000' },
      runs: { type: 'string', default: '3' },
      seed: { type: 'string', default: '1' },
      runtime: { type: 'string', default: 'node' },
      label: { type: 'string' },
      out: { type: 'string' },
      // Internal: the measuring process, with <vault> <userData> <notes>.
      measure: { type: 'boolean', default: false },
    },
  });

  if (values.measure) {
    const [vault, userData, notes] = positionals;
    process.stdout.write(JSON.stringify(await measure(vault!, userData!, Number(notes))));
    return;
  }
  if (positionals.length > 0) throw new Error(`unexpected argument: ${positionals[0]}`);
  const { runtime } = values;
  if (runtime !== 'node' && runtime !== 'electron') throw new Error('runtime must be node or electron');
  const name = `${new Date().toISOString().replace(/[:.]/g, '-')}-${runtime}.json`;
  const out = resolve(values.out ?? join(tmpdir(), 'myelin-bench', name));
  // Results are per machine: they are not committed.
  if (isInside(REPO_ROOT, out)) throw new Error(`output must be outside the repo: ${out}`);
  await mkdir(dirname(out), { recursive: true });

  const report = await runBench({
    sizes: values.sizes.split(',').map(Number),
    runs: Number(values.runs),
    seed: Number(values.seed),
    runtime,
    label: values.label,
    log: (line) => console.error(line),
  });
  await writeFile(out, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  console.log(`${formatReport(report)}\n\nsaved: ${out}`);
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
