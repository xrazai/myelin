// Performance benchmark (AGENTS.md, rule 6). Stage 1: vault scan and index times.
// First layout time of the graph: `bench-layout.ts`.
//   node scripts/bench.ts [--sizes 10000,100000] [--runs 3] [--seed 1]
//                         [--runtime node|electron] [--label <text>] [--out <file outside the repo>]
// Prints a table and saves JSON (default: `<tmp>/myelin-bench/<timestamp>.json`).
// `node scripts/bench.ts --editor` measures typing latency instead (see `bench-editor.ts`),
// and `--graph` the frame time of the graph (see `bench-graph.ts`; needs a GPU).
//
// Each run generates a new vault and measures it in a new process, in this order:
//   scan    `scanVault` alone. File contents are not read.
//   cold    new index; no process has read the notes since they were written. It is not a
//           cold disk: the OS may still hold what was just written.
//   warm    another new index over the same vault, whose notes this process has now read.
//   reopen  the warm index again, nothing changed.
// `cold`, `warm` and `reopen` are `openIndex` + `syncIndex`, which scans the vault itself:
// they include a scan and must not be added to `scan`.
//
// `--runtime electron` measures in the repo's Electron binary as Node
// (ELECTRON_RUN_AS_NODE), not in the app. The vault is always generated by this process.
//
// Run directly by Node (type stripping): erasable TypeScript only.

